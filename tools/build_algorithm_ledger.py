#!/usr/bin/env python
"""Build the ranked-list part of docs/algorithm_ledger.md (section 8C) and
its per-algorithm pages from the CSV import.

    python tools/build_algorithm_ledger.py            # regenerate everything
    python tools/build_algorithm_ledger.py --check    # exit 1 if anything is stale
    python tools/build_algorithm_ledger.py --source path/to/new_export.csv

Reads two files, both committed:

  docs/algorithms/source/*.csv.xz        the import, every field of every row
                                         (.csv, .csv.gz and .csv.xz all read)
  docs/algorithms/implementation_status.csv
                                         hand-maintained: which algorithms
                                         volatility-ai implements, and where

Writes:

  docs/algorithm_ledger.md               the block between the ranked-list
                                         BEGIN/END markers in section 8C
  docs/algorithms/<slug>.md              one page per specific algorithm
  docs/algorithms/concepts/<slug>.md     one page per shared concept of the
                                         title-reconstructed rows, + README.md
  docs/algorithms/ranked/ranks-*.md      the title-reconstructed rows, by rank

--------------------------------------------------------------------
TWO KINDS OF ROW, TWO KINDS OF PAGE

The import of 2026-10-27 has 14,225 rows. 425 of them (ranks 1-425) are
specific algorithms with their own descriptions: each gets a page. The
other 13,800 are what the CSV itself calls "reconstructed from the
algorithm title" -- combinatorial names ("... Scholarly ... MK-1") over
only 378 distinct descriptions, 8,872 citing papers its own review calls
unrelated to trading. A page each would be ~30 MB of near-duplicates, so
they are listed by rank in ranked/ and each links to the page of the
concept it shares. The split is read from the CSV's own "Description
Basis / Confidence" column, not from the rank.

--------------------------------------------------------------------
GENERATED PAGES ARE MARKED; RESEARCHED ONES ARE NOT TOUCHED

Every page this writes starts with GENERATED_MARK. A page without it is
hand-written research (docs/algorithms/time-series-momentum-tsmom.md is
one): the build links to it as "researched" and never overwrites it. To
research an algorithm, replace its generated page and delete the mark
line. Concept pages work the same way: a concepts/<slug>.md without the
mark is research on the concept every member shares, and the shards and
the concept index link to it as researched. A marked page that the
import no longer produces is deleted.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import io
import lzma
import re
import sys
import unicodedata
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "docs" / "algorithm_ledger.md"
PAGES = ROOT / "docs" / "algorithms"
SOURCE = PAGES / "source" / "trading_algorithms_ranked_2026-10-27.csv.xz"
STATUS = PAGES / "implementation_status.csv"

GENERATED_MARK = "<!-- generated by tools/build_algorithm_ledger.py"
BEGIN = "<!-- BEGIN ranked list: generated by tools/build_algorithm_ledger.py -->"
END = "<!-- END ranked list -->"
LEDGER_ANCHOR = "8c-the-ranked-algorithm-list-csv-import"
RECONSTRUCTED = "Low confidence — reconstructed from the algorithm title"
SHARD_SIZE = 1000
DASH = chr(0x2013)  # the ledger writes ranges with an en dash

COLUMNS = {
    "name": "Algorithm Name",
    "rank": "Potential Effectiveness Rank (1 = strongest)",
    "family": "Algorithm Family",
    "description": "Brief Description",
    "original": "Original Brief Description (Before Review)",
    "fit": "Circumstances / Regimes Where It May Fit",
    "vehicles": "Common Fund / Vehicle / Asset Types",
    "data": "Required Data",
    "references": "Source / Implementation Reference URL(s)",
    "caveats": "Implementation Caveats / Notes",
    "ai_rank": "AI Implementability Rank (1 = easiest)",
    "retail_rank": "Retail Advantage vs. Institutions Rank (1 = strongest)",
    "basis": "Description Basis / Confidence",
    "review": "Reference Review Status",
    "review_notes": "Reference Review Notes",
    "alignment": "Metadata Alignment Check",
}
RANKS = ("rank", "ai_rank", "retail_rank")

STATUS_LABELS = {"yes": "Yes", "research": "Research code", "partial": "Partial", "no": "No"}
NOT_MAPPED = {"status": "no", "ledger": "", "code": "", "note": ""}


@dataclass(frozen=True)
class Algorithm:
    name: str
    rank: int
    family: str
    description: str
    original: str
    fit: str
    vehicles: str
    data: str
    references: str
    caveats: str
    ai_rank: int
    retail_rank: int
    basis: str
    review: str
    review_notes: str
    alignment: str

    @property
    def reconstructed(self) -> bool:
        return self.basis.startswith(RECONSTRUCTED)


# ---------------------------------------------------------------- reading


def _open_text(path: Path) -> io.TextIOBase:
    opener = {".xz": lzma.open, ".gz": gzip.open}.get(path.suffix, open)
    return opener(path, "rt", encoding="utf-8-sig", newline="")


def read_source(path: Path) -> list[Algorithm]:
    """Every row, sorted by rank. Ranks must be unique positive integers
    and names unique: both are keys downstream."""
    with _open_text(path) as fh:
        reader = csv.DictReader(fh)
        missing = set(COLUMNS.values()) - set(reader.fieldnames or ())
        if missing:
            raise ValueError(f"{path.name} lacks columns: {sorted(missing)}")
        rows = [
            Algorithm(
                **{
                    key: int(row[col]) if key in RANKS else (row[col] or "").strip()
                    for key, col in COLUMNS.items()
                }
            )
            for row in reader
        ]
    for what, values in (("rank", [a.rank for a in rows]), ("name", [a.name for a in rows])):
        repeated = [v for v, n in Counter(values).items() if n > 1]
        if repeated:
            raise ValueError(f"{path.name}: duplicate {what}s {repeated[:5]}")
    return sorted(rows, key=lambda a: a.rank)


def read_status(path: Path, names: set[str]) -> dict[str, dict[str, str]]:
    """algorithm name -> {status, ledger, code, note}. An algorithm not
    listed is not implemented."""
    with path.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    out: dict[str, dict[str, str]] = {}
    for row in rows:
        name, status = row["algorithm"].strip(), row["status"].strip()
        if name not in names:
            raise ValueError(f"{path.name}: {name!r} is not in the import")
        if status not in STATUS_LABELS:
            raise ValueError(f"{path.name}: {name!r} has status {status!r}")
        if name in out:
            raise ValueError(f"{path.name}: {name!r} is listed twice")
        out[name] = {k: (row.get(k) or "").strip() for k in ("status", "ledger", "code", "note")}
    return out


def split_refs(field: str) -> list[str]:
    """A ';'- or whitespace-separated field: 'module:qualname',
    'package.module' or 'tools/x.py' references."""
    return [r for r in re.split(r"[;\s]+", field) if r]


# ---------------------------------------------------------------- markdown helpers


def slugify(text: str, max_len: int = 80) -> str:
    text = re.sub("[\u2010-\u2015\u2212]", "-", text)  # dashes and minus: 12-1 is not 121
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")
    return slug[:max_len].rstrip("-") or "algorithm"


def unique_slugs(texts: list[str]) -> list[str]:
    seen: Counter[str] = Counter()
    out = []
    for text in texts:
        base = slugify(text)
        seen[base] += 1
        out.append(base if seen[base] == 1 else f"{base}-{seen[base]}")
    return out


def text(value: str) -> str:
    """Free text from the CSV, safe as a markdown paragraph."""
    value = " ".join(value.split())
    return value.replace("<", "&lt;").replace(">", "&gt;") if value else "—"


def cell(value: str) -> str:
    return text(value).replace("|", "\\|")


def links(field: str) -> list[str]:
    """Bullet items for a references field: each URL autolinked, any other
    text kept as written."""
    urls = re.findall(r"https?://[^\s;,]+", field)
    rest = re.sub(r"https?://[^\s;,]+", " ", field)
    rest = " ".join(w for w in re.split(r"[\s;]+", rest) if w)
    return [f"<{u.rstrip('.)')}>" for u in urls] + ([text(rest)] if rest else [])


def code_link(ref: str, prefix: str) -> str:
    """'research.strategies.hrp:hrp_weights' -> a link to the module file."""
    if ref.endswith(".py"):
        path = ref
    else:
        module = ref.partition(":")[0]
        path = module.replace(".", "/") + ".py"
        if not (ROOT / path).is_file():
            path = module.replace(".", "/") + "/__init__.py"
    return f"[`{ref}`]({prefix}{path})"


def status_label(status: dict[str, str]) -> str:
    return STATUS_LABELS[status["status"]]


def ledger_ids(status: dict[str, str]) -> str:
    ids = split_refs(status["ledger"].replace(",", ";"))
    return ", ".join(ids) if ids else "—"


def concept_title(description: str) -> str:
    head = description.split(":", 1)[0].strip()
    head = re.sub(r"^Proposed\s+", "", head)
    return head[:1].upper() + head[1:]


def fmt_range(lo: int, hi: int) -> str:
    return f"{lo:,}{DASH}{hi:,}"


# ---------------------------------------------------------------- pages


def mark(source_name: str, researchable: bool = False) -> str:
    instead = (
        ", or replace this page with a researched one and delete this line" if researchable else ""
    )
    return (
        f"{GENERATED_MARK} from {source_name} and implementation_status.csv. "
        f"Do not edit: change those and re-run{instead}. -->"
    )


def render_card(a: Algorithm, status: dict[str, str], total: int, src: str, date: str) -> str:
    code = [code_link(r, "../../") for r in split_refs(status["code"])]
    lines = [
        mark(src, researchable=True),
        "",
        f"# {text(a.name)}",
        "",
        f"Rank **{a.rank:,}** of {total:,} in the "
        f"[ranked algorithm list](../algorithm_ledger.md#{LEDGER_ANCHOR}) (CSV import of "
        f"{date}). **Not researched yet:** apart from the implementation status, every "
        "line below is the CSV's own text.",
        "",
        "| | |",
        "|---|---|",
        f"| Family | {cell(a.family)} |",
        f"| Potential effectiveness rank | {a.rank:,} (1 = strongest) |",
        f"| AI implementability rank | {a.ai_rank:,} (1 = easiest) |",
        f"| Retail advantage rank | {a.retail_rank:,} (1 = strongest) |",
        f"| Implemented in volatility-ai | **{status_label(status)}** |",
        f"| Ledger entries | {ledger_ids(status)} |",
        f"| Code | {'<br>'.join(code) if code else '—'} |",
        "",
    ]
    if status["note"]:
        lines += [f"**Implementation note:** {text(status['note'])}", ""]
    lines += ["## Description", "", text(a.description), ""]
    if a.original:
        lines += [f"*Before the CSV's description review:* {text(a.original)}", ""]
    for heading, value in (
        ("Where it may fit", a.fit),
        ("Vehicles", a.vehicles),
        ("Required data", a.data),
        ("Caveats", a.caveats),
    ):
        lines += [f"## {heading}", "", text(value), ""]
    lines += ["## References", ""]
    lines += [f"- {item}" for item in links(a.references)] or ["—"]
    lines += [
        "",
        "## Source confidence",
        "",
        f"- **Description basis:** {text(a.basis)}",
        f"- **Reference review:** {text(a.review)} — {text(a.review_notes)}",
        f"- **Metadata alignment:** {text(a.alignment)}",
        "",
    ]
    return "\n".join(lines)


def _counted(values: list[str], render=text) -> list[str]:
    counts = Counter(values)
    if len(counts) == 1:
        return [f"- {render(values[0])} (all {len(values):,})"]
    return [f"- {render(v)} ({n:,})" for v, n in sorted(counts.items(), key=lambda kv: -kv[1])]


def render_concept(
    title: str,
    members: list[Algorithm],
    status: dict[str, dict[str, str]],
    total: int,
    src: str,
    date: str,
) -> str:
    states = Counter(status_label(status.get(a.name, NOT_MAPPED)) for a in members)
    implemented = (
        "None is implemented in volatility-ai."
        if set(states) == {"No"}
        else "Implemented in volatility-ai: "
        + ", ".join(f"{k} {n:,}" for k, n in sorted(states.items()))
        + "."
    )
    lines = [
        mark(src),
        "",
        f"# {text(title)}",
        "",
        f"A concept shared by **{len(members):,}** of the {total:,} algorithms in the "
        f"[ranked algorithm list](../../algorithm_ledger.md#{LEDGER_ANCHOR}) (CSV import of "
        f"{date}); its best-ranked member is #{members[0].rank:,}. The CSV rates every "
        f"member: *{text(members[0].basis)}* {implemented}",
        "",
        "## Description",
        "",
        text(members[0].description),
        "",
        "## What the members' rows say",
        "",
        "Every member's row carries one of the values below; the count says how many.",
        "",
        "**Family**",
        "",
        *_counted([a.family for a in members]),
        "",
    ]
    if any(a.original for a in members):
        lines += ["**Before the CSV's description review**", ""]
        lines += [*_counted([a.original for a in members]), ""]
    for heading, values in (
        ("Where it may fit", [a.fit for a in members]),
        ("Vehicles", [a.vehicles for a in members]),
        ("Required data", [a.data for a in members]),
        ("Caveats", [a.caveats for a in members]),
        ("Metadata alignment check", [a.alignment for a in members]),
    ):
        lines += [f"**{heading}**", "", *_counted(values), ""]
    lines += ["**References and the CSV's review of them**", ""]
    refs = Counter((a.references, a.review, a.review_notes) for a in members)
    for (field, review, notes), n in sorted(refs.items(), key=lambda kv: -kv[1]):
        lines.append(f"- {', '.join(links(field))} — *{text(review)}.* {text(notes)} ({n:,})")
    lines += [
        "",
        "## Members",
        "",
        "| Rank | Algorithm | Family | AI | Retail | Implemented |",
        "|---|---|---|---|---|---|",
    ]
    for a in members:
        state = status_label(status.get(a.name, NOT_MAPPED))
        lines.append(
            f"| {a.rank} | {cell(a.name)} | {cell(a.family)} | {a.ai_rank} | "
            f"{a.retail_rank} | {state} |"
        )
    return "\n".join(lines) + "\n"


def render_concept_index(
    concepts: list[tuple[str, str, list[Algorithm]]], src: str, researched: frozenset[str]
) -> str:
    lines = [
        mark(src),
        "",
        "# Concepts of the title-reconstructed algorithms",
        "",
        f"The {sum(len(m) for _, _, m in concepts):,} title-reconstructed rows of the "
        f"[ranked algorithm list](../../algorithm_ledger.md#{LEDGER_ANCHOR}) share "
        f"{len(concepts):,} descriptions. Each page below holds one description, every "
        "variant of the other fields its members carry, and the members themselves. "
        f"{len(researched):,} of them are researched by hand.",
        "",
        "| Concept | Members | Best rank |",
        "|---|---|---|",
    ]
    for slug, title, members in concepts:
        done = " · **researched**" if slug in researched else ""
        lines.append(
            f"| [{cell(title)}]({slug}.md){done} | {len(members):,} | {members[0].rank:,} |"
        )
    return "\n".join(lines) + "\n"


def render_shard(
    rows: list[Algorithm],
    concept_of: dict[str, str],
    status: dict[str, dict[str, str]],
    total: int,
    src: str,
    researched: frozenset[str],
) -> str:
    lo, hi = rows[0].rank, rows[-1].rank
    lines = [
        mark(src),
        "",
        f"# Ranked algorithm list: ranks {fmt_range(lo, hi)}",
        "",
        f"Title-reconstructed rows of the [ranked algorithm list]"
        f"(../../algorithm_ledger.md#{LEDGER_ANCHOR}) ({total:,} rows in all). The CSV rates "
        f"each one *{text(rows[0].basis)}* Its documentation is the page of the concept "
        "it shares with other rows.",
        "",
        "| Rank | Algorithm | Family | AI | Retail | Implemented | Documentation |",
        "|---|---|---|---|---|---|---|",
    ]
    for a in rows:
        state = status_label(status.get(a.name, NOT_MAPPED))
        slug = concept_of[a.name]
        doc = "**researched** concept" if slug in researched else "concept"
        lines.append(
            f"| {a.rank} | {cell(a.name)} | {cell(a.family)} | {a.ai_rank} | {a.retail_rank} "
            f"| {state} | [{doc}](../concepts/{slug}.md) |"
        )
    return "\n".join(lines) + "\n"


def render_ledger_block(
    specific: list[Algorithm],
    reconstructed: list[Algorithm],
    page_of: dict[str, tuple[str, bool]],
    shards: list[tuple[str, list[Algorithm]]],
    n_concepts: int,
    n_researched: int,
    status: dict[str, dict[str, str]],
    src: str,
) -> str:
    def counts(rows: list[Algorithm]) -> str:
        c = Counter(status.get(a.name, NOT_MAPPED)["status"] for a in rows)
        return " | ".join(f"{c[k]:,}" for k in STATUS_LABELS)

    def band(rows: list[Algorithm]) -> str:
        return fmt_range(rows[0].rank, rows[-1].rank) if rows else "—"

    header = " | ".join(STATUS_LABELS.values())
    lines = [
        BEGIN,
        "",
        f"*Generated from `docs/algorithms/source/{src}` and "
        "`docs/algorithms/implementation_status.csv` by `python tools/build_algorithm_ledger.py`. "
        "Edit those two files, not this block.*",
        "",
        f"| Rows | Algorithms | {header} |",
        "|---|---|" + "---|" * len(STATUS_LABELS),
        f"| Specific (ranks {band(specific)}) | {len(specific):,} | {counts(specific)} |",
        f"| Title-reconstructed (ranks {band(reconstructed)}) | {len(reconstructed):,} "
        f"| {counts(reconstructed)} |",
        f"| All | {len(specific) + len(reconstructed):,} | {counts(specific + reconstructed)} |",
        "",
        "#### Specific algorithms",
        "",
        "| Rank | Algorithm | Family | AI | Retail | Implemented | Ledger | Documentation |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for a in specific:
        slug, researched = page_of[a.name]
        s = status.get(a.name, NOT_MAPPED)
        doc = "**researched**" if researched else "card"
        lines.append(
            f"| {a.rank} | {cell(a.name)} | {cell(a.family)} | {a.ai_rank} | {a.retail_rank} "
            f"| {status_label(s)} | {ledger_ids(s)} | [{doc}](algorithms/{slug}.md) |"
        )
    lines += [
        "",
        "#### Title-reconstructed algorithms",
        "",
        f"Listed by rank on the pages below; each row links to one of {n_concepts:,} "
        f"[concept pages](algorithms/concepts/README.md), {n_researched:,} of them researched.",
        "",
        "| Ranks | Algorithms | Page |",
        "|---|---|---|",
    ]
    for name, rows in shards:
        rng = fmt_range(rows[0].rank, rows[-1].rank)
        lines.append(f"| {rng} | {len(rows):,} | [ranks {rng}](algorithms/ranked/{name}) |")
    lines += ["", END]
    return "\n".join(lines)


# ---------------------------------------------------------------- build


def is_generated(path: Path) -> bool:
    with path.open(encoding="utf-8") as fh:
        return fh.readline().startswith(GENERATED_MARK)


def build(
    source: Path = SOURCE, status_path: Path = STATUS, pages: Path = PAGES, ledger: Path = LEDGER
) -> dict[Path, str]:
    """Every output path -> its full text. Writes nothing."""
    rows = read_source(source)
    status = read_status(status_path, {a.name for a in rows})
    src = source.name
    date_match = re.search(r"\d{4}-\d{2}-\d{2}", src)
    date = date_match.group(0) if date_match else "unknown date"
    total = len(rows)
    specific = [a for a in rows if not a.reconstructed]
    reconstructed = [a for a in rows if a.reconstructed]
    out: dict[Path, str] = {}

    page_of: dict[str, tuple[str, bool]] = {}
    for a, slug in zip(specific, unique_slugs([a.name for a in specific]), strict=True):
        path = pages / f"{slug}.md"
        researched = path.is_file() and not is_generated(path)
        page_of[a.name] = (slug, researched)
        if not researched:
            out[path] = render_card(a, status.get(a.name, NOT_MAPPED), total, src, date)

    by_description: dict[str, list[Algorithm]] = {}
    for a in reconstructed:
        by_description.setdefault(a.description, []).append(a)
    groups = sorted(by_description.values(), key=lambda m: m[0].rank)
    titles = [concept_title(m[0].description) for m in groups]
    concepts = list(zip(unique_slugs(titles), titles, groups, strict=True))
    concept_of = {a.name: slug for slug, _, members in concepts for a in members}
    researched_concepts = set()
    for slug, title, members in concepts:
        path = pages / "concepts" / f"{slug}.md"
        if path.is_file() and not is_generated(path):
            researched_concepts.add(slug)
        else:
            out[path] = render_concept(title, members, status, total, src, date)
    researched = frozenset(researched_concepts)
    if concepts:
        out[pages / "concepts" / "README.md"] = render_concept_index(concepts, src, researched)

    shards = []
    for i in range(0, len(reconstructed), SHARD_SIZE):
        chunk = reconstructed[i : i + SHARD_SIZE]
        name = f"ranks-{chunk[0].rank:05d}-{chunk[-1].rank:05d}.md"
        shards.append((name, chunk))
        out[pages / "ranked" / name] = render_shard(
            chunk, concept_of, status, total, src, researched
        )

    current = ledger.read_text(encoding="utf-8")
    if current.count(BEGIN) != 1 or current.count(END) != 1:
        raise ValueError(f"{ledger.name} needs exactly one {BEGIN!r} and one {END!r}")
    head, rest = current.split(BEGIN)
    tail = rest.split(END, 1)[1]
    block = render_ledger_block(
        specific, reconstructed, page_of, shards, len(concepts), len(researched), status, src
    )
    out[ledger] = head + block + tail
    return out


def stale_generated(pages: Path, outputs: dict[Path, str]) -> list[Path]:
    """Marked pages the import no longer produces."""
    found = [*pages.glob("*.md"), *pages.glob("concepts/*.md"), *pages.glob("ranked/*.md")]
    return sorted(p for p in found if p not in outputs and is_generated(p))


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--source", type=Path, default=SOURCE)
    p.add_argument("--status", type=Path, default=STATUS)
    p.add_argument("--check", action="store_true", help="report stale output; write nothing")
    args = p.parse_args(argv)

    outputs = build(args.source, args.status)
    changed = [
        path
        for path, content in outputs.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]
    stale = stale_generated(PAGES, outputs)
    if args.check:
        for path in changed:
            print(f"out of date: {path.relative_to(ROOT)}")
        for path in stale:
            print(f"no longer generated: {path.relative_to(ROOT)}")
        return 1 if changed or stale else 0
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
    for path in stale:
        path.unlink()
    print(f"{len(outputs):,} outputs: {len(changed):,} written, {len(stale):,} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
